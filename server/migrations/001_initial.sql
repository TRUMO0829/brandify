-- Run in Supabase SQL Editor. Existing tables are preserved; review their columns separately.
CREATE TABLE IF NOT EXISTS public.admin (
 admin_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username text UNIQUE NOT NULL, password_hash text NOT NULL
);
CREATE TABLE IF NOT EXISTS public.service (
 service_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 title text NOT NULL, icon text, description text, bullets text DEFAULT '[]',
 steps text DEFAULT '[]', kpi text, created_at timestamptz DEFAULT now(), updated_at timestamptz DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.portfolio (
 portfolio_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 title text NOT NULL, category text, description text, image text, challenge text,
 solution text, timeline text, result text, created_at timestamptz DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.inquiry (
 inquiry_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 service_id bigint NOT NULL REFERENCES public.service(service_id),
 customer_name text NOT NULL, customer_phone text NOT NULL, customer_email text,
 company text, budget text, message text, inquiry_date timestamptz DEFAULT now(),
 status text NOT NULL DEFAULT 'Pending' CHECK (status IN ('Pending','Contacted','Done'))
);
ALTER TABLE public.admin ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.service ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.portfolio ENABLE ROW LEVEL SECURITY;
